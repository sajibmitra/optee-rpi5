#!/usr/bin/env python3
"""Train fixed-point TinyML and QAI classifiers on the HAI supervised split."""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_score, recall_score

SCALE = 1000
N = 16


def pairwise(x: np.ndarray) -> np.ndarray:
    cols = [x, np.stack([x[:, i] * x[:, (i + 1) % N] for i in range(N)], axis=1)]
    return np.concatenate(cols, axis=1)


def quantize(w: np.ndarray, b: float) -> tuple[np.ndarray, int]:
    return np.rint(w * SCALE).astype(np.int32), int(np.rint(b * SCALE))


def fp_tinyml(x: np.ndarray, w: np.ndarray, b: int) -> np.ndarray:
    xm = np.rint(x * SCALE).astype(np.int64)
    acc = b * SCALE + xm @ w.astype(np.int64)
    return (acc > 0).astype(np.int8)


def fp_qai(x: np.ndarray, theta: np.ndarray, gamma: np.ndarray, b: int) -> np.ndarray:
    xm = np.rint(x * SCALE).astype(np.int64)
    acc = np.full(len(x), b * SCALE, dtype=np.int64)
    acc += xm @ theta.astype(np.int64)
    for i in range(N):
        j = (i + 1) % N
        acc += (gamma[i].astype(np.int64) * xm[:, i] * xm[:, j]) // SCALE
    return (acc > 0).astype(np.int8)


def report(name: str, y: np.ndarray, pred: np.ndarray) -> None:
    cm = confusion_matrix(y, pred, labels=[0, 1])
    print(
        f"{name} acc={accuracy_score(y, pred):.4f} "
        f"prec={precision_score(y, pred, zero_division=0):.4f} "
        f"rec={recall_score(y, pred, zero_division=0):.4f} "
        f"f1={f1_score(y, pred, zero_division=0):.4f} cm={cm.tolist()}"
    )


def c_array(name: str, vals: np.ndarray) -> str:
    body = ", ".join(str(int(v)) for v in vals)
    return f"static const int32_t {name}[QAI_HAI_FEAT] = {{\n\t{body}\n}};"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", type=Path, default=Path("/tmp/hai-tee"))
    ap.add_argument("--header", type=Path, required=True)
    args = ap.parse_args()
    xtr = np.fromfile(args.data / "sup_x.bin", np.float32).reshape(-1, N)
    ytr = np.fromfile(args.data / "sup_y.bin", np.int8)
    xte = np.fromfile(args.data / "classical_query.bin", np.float32).reshape(-1, N)
    yte = np.fromfile(args.data / "labels.bin", np.int8)
    print(f"train {len(ytr)} attack {int(ytr.sum())} test {len(yte)} attack {int(yte.sum())}")

    tin = LogisticRegression(max_iter=500, class_weight="balanced")
    tin.fit(xtr, ytr)
    tw, tb = quantize(tin.coef_.ravel(), float(tin.intercept_[0]))
    pred_t = fp_tinyml(xte, tw, tb)
    report("tinyml_fp", yte, pred_t)

    q = LogisticRegression(max_iter=500, class_weight="balanced")
    q.fit(pairwise(xtr), ytr)
    coef = q.coef_.ravel()
    theta, gamma = quantize(coef[:N], 0)
    gamma, _ = quantize(coef[N:], 0)
    qb = int(np.rint(float(q.intercept_[0]) * SCALE))
    pred_q = fp_qai(xte, theta, gamma, qb)
    report("qai_fp", yte, pred_q)

    xm = np.rint(xte * SCALE).astype(np.int32)
    (args.data / "test_milli.bin").write_bytes(np.ascontiguousarray(xm).tobytes())
    text = "\n".join(
        [
            "/* SPDX-License-Identifier: BSD-2-Clause */",
            "/* Generated by tools/hai_tinyml_train.py from HAI 20.07. */",
            "#ifndef QAI_MODEL_HAI_H",
            "#define QAI_MODEL_HAI_H",
            "#include <stdint.h>",
            "#include <qai_ta.h>",
            c_array("hai_tinyml_w", tw),
            f"static const int32_t hai_tinyml_bias = {tb};",
            c_array("hai_pairwise_fake_theta", theta),
            c_array("hai_pairwise_fake_gamma", gamma),
            f"static const int32_t hai_pairwise_fake_bias = {qb};",
            "#endif",
            "",
        ]
    )
    args.header.write_text(text)
    print(f"wrote {args.header}")


if __name__ == "__main__":
    main()
